"""Synthetic Indian transaction dataset generator.

Produces a REALISTIC-LOOKING but fully synthetic dataset (no real people's
financial data) with Indian merchants, cities, and payment methods, including
legitimate / suspicious-looking / fraudulent behavioral patterns.

Labels are generated by the SAME risk patterns the feature space encodes
(amount deviation, night hours, new merchant/location, velocity bursts), with
random noise so the model must actually learn instead of copying rules.
"""
from __future__ import annotations

import random
from datetime import datetime, timedelta

import numpy as np
import pandas as pd

MERCHANTS = {
    "Food & Dining": ["Swiggy", "Zomato", "Dominos", "Local Tiffin Center", "Cafe Coffee Day"],
    "Groceries": ["Blinkit", "Zepto", "BigBasket", "DMart", "Kirana Store"],
    "Shopping": ["Amazon", "Flipkart", "Myntra", "Meesho", "Croma"],
    "Transport": ["Uber", "Rapido", "Ola", "IRCTC", "Metro Card Recharge"],
    "Entertainment": ["BookMyShow", "Netflix", "Spotify", "Steam"],
    "Utilities": ["Airtel Recharge", "Jio Recharge", "Electricity Bill", "Gas Booking"],
    "Health": ["PharmEasy", "Apollo Pharmacy", "Local Clinic"],
    "Electronics": ["Croma Store", "Reliance Digital", "Vijay Sales"],
}

CATEGORIES = list(MERCHANTS.keys())
LOCATIONS = [
    "Raipur", "Bhilai", "Delhi", "Mumbai", "Bangalore",
    "Hyderabad", "Pune", "Kolkata", "Chennai",
]
PAYMENT_METHODS = ["UPI", "Debit Card", "Credit Card", "Wallet", "Net Banking"]
DEVICE_TYPES = ["mobile", "desktop", "tablet"]

# Fraud-actor merchants / categories (deliberately unusual for a normal user)
FRAUD_MERCHANTS = ["QuickCash Electronics", "InstantRecharge.xyz", "Unknown Electronics",
                   "PayNow Deals", "LuckyWin Offers"]
FRAUD_CATEGORIES = ["Electronics", "Gift Cards", "Wallet Top-up", "Other"]

CATEGORY_AMOUNT_RANGE = {
    "Food & Dining": (80, 900),
    "Groceries": (150, 2500),
    "Shopping": (400, 8000),
    "Transport": (30, 600),
    "Entertainment": (100, 1500),
    "Utilities": (200, 3000),
    "Health": (150, 4000),
    "Electronics": (1500, 45000),
}


def generate_synthetic_dataset(
    n_users: int = 40,
    txns_per_user: int = 120,
    fraud_rate: float = 0.06,
    random_seed: int = 42,
) -> pd.DataFrame:
    """Generate a synthetic labeled transaction dataset with target `is_fraud`."""
    rng = random.Random(random_seed)
    np_rng = np.random.default_rng(random_seed)
    now = datetime.now().replace(minute=0, second=0, microsecond=0)
    rows: list[dict] = []

    for user_idx in range(n_users):
        home_city = rng.choice(LOCATIONS[:4] + [rng.choice(LOCATIONS)])
        fav_categories = rng.sample(CATEGORIES, k=rng.randint(3, 5))
        fav_merchants = [rng.choice(MERCHANTS[c]) for c in fav_categories]
        fav_methods = rng.sample(PAYMENT_METHODS, k=rng.randint(1, 3))
        base_amount = rng.uniform(120, 900)
        active_start, active_end = rng.choice([(7, 23), (8, 22), (9, 23), (6, 23)])

        n_fraud = max(1, int(txns_per_user * fraud_rate))
        fraud_slots = set(rng.sample(range(txns_per_user), n_fraud))

        last_dt = now - timedelta(days=rng.randint(60, 120))
        for i in range(txns_per_user):
            is_fraud = i in fraud_slots
            if is_fraud:
                row = _make_fraud_row(rng, np_rng, user_idx, home_city, last_dt)
            else:
                row = _make_legit_row(
                    rng, np_rng, user_idx, home_city, fav_categories, fav_merchants,
                    fav_methods, base_amount, active_start, active_end, last_dt,
                )
            # small label noise so the model must learn patterns, not rules
            row["is_fraud"] = 1 - int(is_fraud) if rng.random() < 0.01 else int(is_fraud)
            last_dt = row["transaction_datetime"] + timedelta(minutes=rng.randint(30, 24 * 60))
            rows.append(row)

    frame = pd.DataFrame(rows)
    frame["transaction_datetime"] = pd.to_datetime(frame["transaction_datetime"])
    return frame.sort_values("transaction_datetime").reset_index(drop=True)


def _make_legit_row(rng, np_rng, user_idx, home_city, fav_categories, fav_merchants,
                    fav_methods, base_amount, active_start, active_end, after_dt):
    category = rng.choice(fav_categories)
    merchant = rng.choice(fav_merchants) if fav_merchants else rng.choice(MERCHANTS[category])
    lo, hi = CATEGORY_AMOUNT_RANGE.get(category, (100, 2000))
    amount = float(np.clip(np_rng.normal(base_amount, base_amount * 0.45), lo, hi))
    hour = rng.randint(active_start, active_end)
    dt = after_dt + timedelta(days=rng.randint(0, 3),
                              hours=max(0, hour - after_dt.hour),
                              minutes=rng.randint(0, 59))
    location = home_city if rng.random() < 0.85 else rng.choice(LOCATIONS)
    return {
        "user_id": f"user_{user_idx:03d}",
        "transaction_id": f"TXN{rng.randint(10**8, 10**9 - 1)}",
        "amount": round(amount, 2),
        "merchant": merchant,
        "merchant_category": category,
        "location": location,
        "payment_method": rng.choice(fav_methods),
        "device_type": rng.choice(DEVICE_TYPES),
        "transaction_datetime": dt,
    }


def _make_fraud_row(rng, np_rng, user_idx, home_city, after_dt):
    """Fraud pattern: high amount + night hour + new merchant + new location -
    the signals the feature space encodes."""
    style = rng.random()
    amount = float(np_rng.uniform(5000, 60000)) if style < 0.7 else float(np_rng.uniform(500, 2000))
    hour = rng.choice([0, 1, 2, 3, 4, 23]) if style < 0.6 else rng.randint(9, 22)
    dt = (after_dt + timedelta(minutes=rng.choice([1, 2, 5, 45, 120, 600]))).replace(hour=hour)
    merchant = rng.choice(FRAUD_MERCHANTS)
    category = rng.choice(FRAUD_CATEGORIES)
    location = rng.choice([l for l in LOCATIONS if l != home_city]) if rng.random() < 0.6 else home_city
    return {
        "user_id": f"user_{user_idx:03d}",
        "transaction_id": f"TXN{rng.randint(10**8, 10**9 - 1)}",
        "amount": round(amount, 2),
        "merchant": merchant,
        "merchant_category": category,
        "location": location,
        "payment_method": rng.choice(["UPI", "Credit Card", "Wallet"]),
        "device_type": rng.choice(DEVICE_TYPES),
        "transaction_datetime": dt,
    }
